#!/usr/bin/env bash
# Regenerate the work queue from the live GitHub state (labels, linked PRs, spec files).
#
#   scripts/update-queue.sh            # writes docs/QUEUE.md (git-ignored, local view)
#   scripts/update-queue.sh --stdout   # prints the queue (used by .github/workflows/queue.yml)
#
# Requires: gh (authenticated). Run from the repository root.
set -euo pipefail

repo="${GITHUB_REPOSITORY:-$(gh repo view --json nameWithOwner -q .nameWithOwner)}"
out="docs/QUEUE.md"
[[ "${1:-}" == "--stdout" ]] && out="/dev/stdout"

# --- helpers ---------------------------------------------------------------

# $1 = issue number -> the matching docs/specs/NNNN-*.md path (zero-padded), or an em dash.
spec_ref() {
  local f
  f="$(compgen -G "docs/specs/$(printf '%04d' "$1")-*.md" | head -1 || true)"
  printf '%s' "${f:-—}"
}

# $1 = issue number -> "PR #N" if an open PR body says "Closes #N", else an em dash.
pr_ref() {
  local n
  n="$(gh pr list --repo "$repo" --state open --search "\"Closes #$1\" in:body" \
        --json number,body --jq "[.[] | select(.body | test(\"(?i)closes #$1\\\\b\"))][0].number // empty" \
        2>/dev/null || true)"
  if [[ -n "$n" ]]; then printf 'PR #%s' "$n"; else printf '—'; fi
}

# --- rows ------------------------------------------------------------------

ready="$(mktemp)"
waiting="$(mktemp)"
trap 'rm -f "$ready" "$waiting"' EXIT

# One API call: "number<TAB>title<TAB>label,label,…", oldest issue first (= roadmap order).
gh issue list --repo "$repo" --state open --limit 1000 --json number,title,labels \
  --jq 'sort_by(.number)[] | "\(.number)\t\(.title)\t\([.labels[].name] | join(","))"' |
while IFS=$'\t' read -r n title labels; do
  state="$(tr ',' '\n' <<<"$labels" | grep -xE 'to-spec|to-dev|in-review' | head -1 || true)"
  [[ -n "$state" ]] || continue

  if [[ "$state" == "in-review" ]] && tr ',' '\n' <<<"$labels" | grep -qx 'approved'; then
    printf '| #%s %s | in-review | Merge %s (approved by the architect) | maintainer |\n' "$n" "$title" "$(pr_ref "$n")" >> "$waiting"
    continue
  fi

  if tr ',' '\n' <<<"$labels" | grep -qx 'question'; then
    ref="$(pr_ref "$n")"
    [[ "$ref" == "—" ]] && ref="the issue"
    printf '| #%s %s | %s | Answer the question in %s | architect |\n' "$n" "$title" "$state" "$ref" >> "$waiting"
    continue
  fi

  case "$state" in
    to-spec)
      printf '| #%s %s | to-spec | Write spec + prototype, then set `to-dev` | architect | %s |\n' \
        "$n" "$title" "$(spec_ref "$n")" >> "$ready" ;;
    to-dev)
      printf '| #%s %s | to-dev | Implement / address review; open or update the PR, then set `in-review` | developer | %s |\n' \
        "$n" "$title" "$(spec_ref "$n")" >> "$ready" ;;
    in-review)
      ref="$(pr_ref "$n")"
      printf '| #%s %s | in-review | Review %s against spec + prototype; approve and merge, or request changes (`to-dev`) | architect | %s |\n' \
        "$n" "$title" "$ref" "$ref" >> "$ready" ;;
  esac
done

# --- output ----------------------------------------------------------------

{
cat <<'EOF'
# Work queue

Generated by `scripts/update-queue.sh` from the live GitHub state (open issues, their state
labels, linked PRs and `docs/specs/`). **Do not edit or commit it** — it is git-ignored.
Regenerate it before acting; the same view is published in the summary of every
"Update queue" workflow run.

Agents: `architect` (specs, prototypes, answers, reviews, merges) and `developer`
(implements, asks, opens PRs). Roles: `docs/agents/architect.md`, `docs/agents/developer.md`.

```
to-spec ──► to-dev ──► in-review ──► closed (merged PR with "Closes #N")
               ▲           │
               └───────────┘  changes requested
```

`question` is orthogonal to the state: it moves the row to **Waiting** until the architect
answers and removes it. `approved` (with `in-review`) moves it to **Waiting** for the maintainer's merge. Only the architect promotes backlog issues to `to-dev`, one at a time.

## Ready (take the topmost row for your role)

| Issue | State | Next action | Agent | Ref |
|-------|-------|-------------|-------|-----|
EOF
cat "$ready"
cat <<'EOF'

## Waiting

| Issue | State | Waiting for | Agent |
|-------|-------|-------------|-------|
EOF
cat "$waiting"
} > "$out"
